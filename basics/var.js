let a = 5; 
// This is a variable declaration and initialization. 
// The variable 'a' is assigned the value 5.  

let b = 10; 
// This is another variable declaration and initialization. 
// The variable 'b' is assigned the value 10.

let c = a + b; 
// The variable 'c' is assigned the value of 'a' plus 'b', 
// which is 15.

console.log(c); 
// This line outputs the value of 'c' to the console, 
// which is 15.

let n = "Shubh"; 
// This is a variable declaration and initialization. 
// The variable 'n' is assigned the string value "Shubh".

console.log(n);
// This line outputs the value of 'n' to the console,
// which is "Shubh".

let isActive = true; 
// This is a variable declaration and initialization. 
// The variable 'isActive' is assigned the boolean value true.

console.log(isActive); 
// This line outputs the value of 'isActive' to the console,
// which is true.

let fruits = ["apple", "banana", "cherry"]; 
// This is a variable declaration and initialization. 
// The variable 'fruits' is assigned an array 
// containing three string values.

console.log(fruits); 
// This line outputs the value of 'fruits' to the console, 
// which is ["apple", "banana", "cherry"].

let person = { name: "Alice", age: 30 }; 
// This is a variable declaration and initialization. 
// The variable 'person' is assigned an object 
// with properties 'name' and 'age'.

console.log(person); 
// This line outputs the value of 'person' to the console, 
// which is { name: "Alice", age: 30 }.

let x; 
// This is a variable declaration without initialization. 
// The variable 'x' is declared but not assigned a value.

console.log(x); 
// This line outputs the value of 'x' to the console,
// which is undefined.

x = 20; 
// This line assigns the value 20 
// to the previously declared variable 'x'.

console.log(x); 
// This line outputs the value of 'x' to the console, 
// which is now 20. 

const PI = 3.14159; 
// This is a constant declaration and initialization.
// The constant 'PI' is assigned the value 3.14159.

console.log(PI); 
// This line outputs the value of 'PI' to the console, 
// which is 3.14159.   

// PI = 3.14; 
// This line attempts to reassign the value of the constant 'PI', 
// which will result in an error 
// "TypeError: Assignment to constant variable." 
// because constants cannot be reassigned.

var y = 50;
 // This is a variable declaration and initialization using 'var'. 
 // The variable 'y' is assigned the value 50.

console.log(y); 
// This line outputs the value of 'y' to the console, 
// which is 50.

y = 100; 
// This line reassigns the value of 'y' to 100.

console.log(y); 
// This line outputs the new value of 'y' to the console, 
// which is now 100. 